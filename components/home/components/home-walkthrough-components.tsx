const MotionBox = chakra(motion.div, {
  /**
   * Allow motion props and the children prop to be forwarded.
   * All other chakra props not matching the motion props will still be forwarded.
   */
  shouldForwardProp: (prop) => isValidMotionProp(prop) || prop === 'children',
});

const AUTO_GENERATED_REPORTS = [
  { id: 'ft', img: '/reports/feature-release.svg', type: 'Report', title: 'Feature release' },
  { id: 'ac', img: '/reports/active-companies.svg', type: 'Report', title: 'Active companies' },
  { id: 'mru', img: '/reports/most-retained-users.svg', type: 'Insight', title: 'Most retained users' },
  { id: 'pu', img: '/reports/power-users.svg', type: 'Report', title: 'Power users' },
  { id: 'cr', img: '/reports/company-retention.svg', type: 'Report', title: 'Company retention' },
  { id: 'usa', img: '/reports/users-slipping-away.svg', type: 'Insight', title: 'Churn risk users' },
];

function AutoGeneratedReports() {
  const [currentReports, setCurrentReports] = useState(AUTO_GENERATED_REPORTS);

  useEffect(() => {
    const interval = setInterval(() => {
      const newReports = [...currentReports];
      const first = newReports.shift();
      newReports.push(first);
      setCurrentReports(newReports);
    }, 2000);

    return () => clearInterval(interval);
  }, [currentReports]);

  return (
    <Flex flexDir="column" align="center" bg="#F7F8FA" h="full">
      <VStack spacing={4} w="full" h="full" pl={4} py={4} overflow="hidden">
        <AnimatePresence>
          {currentReports.map((item) => (
            <MotionBox
              key={item.id}
              layout
              animate={{ scale: 1, opacity: 1 }}
              exit={{ scale: 0.8, opacity: 0 }}
              w="full"
              bg="white"
              border="2px"
              borderColor="purple.300"
              borderRightWidth={0}
              borderRadius="6px"
              borderRightRadius={0}
              shadow="0px 2px 4px rgba(104, 104, 247, 0.2)"
              py={4}
              pl={4}
              flexShrink={0}
            >
              <HStack spacing={4}>
                <Image src={item.img} alt="report" boxSize="80px" />
                <VStack align="start" spacing={1}>
                  <Text fontSize="xs" color="#6A6D7D" whiteSpace="nowrap" textTransform="uppercase">
                    {item.type}
                  </Text>
                  <Text fontWeight="semibold" color="#070B1F">
                    {item.title}
                  </Text>
                </VStack>
              </HStack>
            </MotionBox>
          ))}
        </AnimatePresence>
      </VStack>
    </Flex>
  );
}

